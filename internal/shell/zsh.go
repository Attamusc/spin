// Package shell generates shell integration scripts for spin.
package shell

import (
	"bytes"
	"fmt"
	"text/template"
)

// ZshConfig holds the parameters for generating the zsh integration script.
type ZshConfig struct {
	// SpinPath is the absolute path to the spin binary.
	// If empty, "spin" is used (relies on PATH).
	SpinPath string
}

// GenerateZsh renders the zsh shell integration script.
func GenerateZsh(cfg ZshConfig) (string, error) {
	spinCmd := cfg.SpinPath
	if spinCmd == "" {
		spinCmd = "spin"
	}

	tmpl, err := template.New("zsh").Parse(zshTemplate)
	if err != nil {
		return "", fmt.Errorf("failed to parse zsh template: %w", err)
	}

	data := struct {
		SpinCmd string
	}{
		SpinCmd: spinCmd,
	}

	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, data); err != nil {
		return "", fmt.Errorf("failed to execute zsh template: %w", err)
	}

	return buf.String(), nil
}

const zshTemplate = `# spin shell integration — generated by 'spin shell-init zsh'
# Add to your .zshrc:  eval "$(spin shell-init zsh)"

# ============================================================================
# Project list cache (stale-while-revalidate)
# ============================================================================

_SPIN_CACHE_TTL=${_SPIN_CACHE_TTL:-1800}  # 30 minutes

_spin_cache_file() {
  echo "${XDG_CACHE_HOME:-$HOME/.cache}/spin/projects.cache"
}

_spin_cache_age() {
  local cache_file="$(_spin_cache_file)"
  [[ -f "$cache_file" ]] || { echo 999999; return; }
  local mtime=$(stat -f %m "$cache_file" 2>/dev/null || echo 0)
  local now=$(date +%s)
  echo $((now - mtime))
}

_spin_refresh_cache() {
  local cache_file="$(_spin_cache_file)"
  local cache_dir="${cache_file:h}"
  [[ -d "$cache_dir" ]] || mkdir -p "$cache_dir"
  local tmp="${cache_file}.tmp.$$"
  command {{.SpinCmd}} list --format plain 2>/dev/null > "$tmp" && mv "$tmp" "$cache_file"
}

_spin_refresh_cache_async() {
  if [[ -v _SPIN_CACHE_REFRESH_PID ]] && kill -0 $_SPIN_CACHE_REFRESH_PID 2>/dev/null; then
    return
  fi
  ( _spin_refresh_cache ) &!
  _SPIN_CACHE_REFRESH_PID=$!
}

# Returns cached project list, refreshing async if stale
_spin_cached_projects() {
  local cache_file="$(_spin_cache_file)"
  if [[ ! -f "$cache_file" ]]; then
    _spin_refresh_cache
  elif [[ $(_spin_cache_age) -gt $_SPIN_CACHE_TTL ]]; then
    _spin_refresh_cache_async
  fi
  [[ -f "$cache_file" ]] && cat "$cache_file"
}

# ============================================================================
# Shell function wrapper
# ============================================================================

spin() {
  # Commands that don't produce paths — pass through directly
  case "$1" in
    ""|help|completion|shell-init)
      command {{.SpinCmd}} "$@"
      return $?
      ;;
  esac

  # Commands that print a directory path as the last stdout line
  case "$1" in
    go|new|clone|git-clone)
      local output exit_code
      output=$(command {{.SpinCmd}} "$@" 2>&1)
      exit_code=$?

      if [[ $exit_code -eq 0 ]]; then
        # The last line of stdout is the target path
        local last_line="${output##*$'\n'}"
        if [[ -d "$last_line" ]]; then
          # Print any preceding lines (informational output) to stderr
          local preceding="${output%$'\n'*}"
          if [[ -n "$preceding" && "$preceding" != "$last_line" ]]; then
            echo "$preceding" >&2
          fi
          # Invalidate cache after directory-changing operations
          local cache_file="$(_spin_cache_file)"
          [[ -f "$cache_file" ]] && rm -f "$cache_file"
          builtin cd "$last_line"
          return 0
        fi
      fi

      # Non-zero exit or no valid path — show everything
      [[ -n "$output" ]] && echo "$output" >&2
      return $exit_code
      ;;
  esac

  # All other commands — normal passthrough
  command {{.SpinCmd}} "$@"
}

# ============================================================================
# fzf project picker widget (Ctrl+Space)
# ============================================================================

if command -v fzf >/dev/null 2>&1; then
  _spin_fzf_widget() {
    local selected
    selected=$(_spin_cached_projects | fzf \
      --height=40% \
      --layout=reverse \
      --border \
      --prompt="project> " \
      --preview='echo {}')

    if [[ -n "$selected" ]]; then
      BUFFER="spin go $selected"
      zle accept-line
    fi
    zle reset-prompt
  }
  zle -N _spin_fzf_widget
  bindkey '^ ' _spin_fzf_widget
fi

# ============================================================================
# Completion helpers (used by fzf widget; full completion via cobra below)
# ============================================================================

_spin_complete_projects() {
  local -a projects
  projects=(${(f)"$(_spin_cached_projects)"})
  compadd -a projects
}

# ============================================================================
# Fuzzy completion override for spin (wraps cobra-generated completion)
# ============================================================================
# Cobra's generated completion handles prefix matching well (progressive
# completion, case sensitivity from user's zstyle, etc). We wrap it here:
# try cobra first, and if it finds no matches for a project argument,
# fall back to fuzzy completion via spin's __complete endpoint + compadd -U.

_spin() {
  # Try cobra's standard completion first — handles prefix matching,
  # progressive completion (att<TAB> → Attamusc/ → keep typing), and
  # respects the user's zstyle matcher configuration.
  _spin_cobra && return 0

  # Cobra found no prefix matches. For project-aware subcommands,
  # fall back to fuzzy completion.
  local subcmd="${words[2]}"
  case "$subcmd" in
    go|dev|up|down|status|logs|open|new|clone|db)
      if (( CURRENT == 3 )); then
        local cur="${words[CURRENT]}"
        local -a completions
        local out
        out=$(command {{.SpinCmd}} __complete "${subcmd}" "${cur}" 2>/dev/null)

        # Parse completions (skip the last line which is the directive ":N")
        while IFS='' read -r line; do
          [[ "${line}" == :* ]] && continue
          [[ -n "${line}" ]] && completions+=("${line%%$'\t'*}")
        done <<< "${out}"

        if (( ${#completions} > 0 )); then
          compadd -U -- "${completions[@]}"
          return 0
        fi
      fi
      ;;
  esac
  return 1
}

# Load cobra's generated completion under a different name so we can delegate
eval "$(command {{.SpinCmd}} completion zsh 2>/dev/null | sed -e '/^#compdef/d' -e '/^compdef/d' -e 's/^_spin()/_spin_cobra()/' -e 's/"_spin"/"_spin_cobra"/g' -e 's/^    _spin$/    _spin_cobra/')"

compdef _spin spin
`
